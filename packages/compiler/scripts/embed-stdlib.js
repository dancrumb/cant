// Embed the standard library's Cant declarations (../stdlib/*.cant) in the compiler, as
// src/generated/stdlib.ts, so they are part of the compiled JavaScript, and of bundles such as the
// VS Code extension's language server, rather than files read at runtime.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const directory = join(root, 'stdlib');
const sources = readdirSync(directory)
  .filter((file) => file.endsWith('.cant'))
  .sort()
  .map((file) => [basename(file, '.cant'), readFileSync(join(directory, file), 'utf8')]);

const output = join(root, 'src', 'generated', 'stdlib.ts');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  [
    '// Generated by scripts/embed-stdlib.js from stdlib/*.cant. Do not edit.',
    '',
    '/** The Cant source of each standard library module that has one, by module name. */',
    `export const STANDARD_SOURCES: ReadonlyMap<string, string> = new Map(${JSON.stringify(sources, null, 2)});`,
    '',
  ].join('\n'),
);
